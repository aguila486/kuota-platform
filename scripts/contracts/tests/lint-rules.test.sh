#!/usr/bin/env bash
# Prueba las reglas de Redocly del contrato (T023): cada fixture defectuoso debe fallar por la regla esperada y el
# fixture válido debe pasar. Uso: scripts/contracts/tests/lint-rules.test.sh
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
FIXTURES="$ROOT/scripts/contracts/tests/fixtures/lint"
CONFIG="$ROOT/contracts/openapi/redocly.yaml"
FAILED=0

lint() { (cd "$ROOT" && pnpm exec redocly lint --config "$CONFIG" "$FIXTURES/$1.yaml" 2>&1); }

expect_rule() { # fixture regla
  local output status
  output="$(lint "$1")"; status=$?
  if [ "$status" -ne 0 ] && grep -q "Error was generated by the $2 rule" <<<"$output"; then
    echo "  ✓ $1 → rechazado por $2"
  else
    echo "  ✗ $1: se esperaba un error de $2 (exit $status)"; FAILED=$((FAILED + 1))
  fi
}

echo "Reglas de lint del contrato"
if lint valid >/dev/null; then echo "  ✓ valid → aceptado"; else echo "  ✗ valid debería pasar"; FAILED=$((FAILED + 1)); fi
expect_rule idempotency-missing kuota/idempotency-key-required
expect_rule financial-missing kuota/idempotency-key-required
expect_rule error-not-problem kuota/problem-json-errors
expect_rule money-as-number kuota/money-via-ref
expect_rule unresolved-ref no-unresolved-refs
expect_rule invalid-schema struct

[ "$FAILED" -eq 0 ] && echo "Resultado: todas las reglas se comportan como se espera." || echo "Resultado: $FAILED caso(s) fallaron."
exit "$FAILED"
